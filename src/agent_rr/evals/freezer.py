"""Freeze a tape into a standalone, zero-API-cost pytest behavioral micro-eval (§5.4, D17)."""

import fnmatch
import json
import os
import sqlite3
import tempfile
from pathlib import Path

from agent_rr import __version__
from agent_rr.models import Step, TapeMeta
from agent_rr.tape.store import read_steps
from agent_rr.testing import edited_paths, tool_sequence

PROTECTED_GLOBS = (
    ".github/workflows/**",
    "migrations/**",
    "*.lock",
    ".env*",
    "AGENTS.md",
    "CLAUDE.md",
)

_HEADER = '''"""Frozen behavioral micro-eval generated by agent-rr {version}.

Source tape_id: {tape_id}
Base commit: {base}
Total steps: {steps}
Token usage: {tokens_in} input / {tokens_out} output

Tape under test: $AGENT_RR_TAPE_PATH when set (the run being evaluated), otherwise the
reference tape copied next to this file as {tape_name}. If CI needs the reference tape,
commit it and make sure *.tape is not gitignored in this directory.
"""

import os
import pathlib

import pytest
from agent_rr import testing

REFERENCE_TAPE = pathlib.Path(__file__).with_suffix(".tape")
TAPE = pathlib.Path(os.environ.get("AGENT_RR_TAPE_PATH") or REFERENCE_TAPE)


@pytest.fixture(scope="module")
def tape() -> pathlib.Path:
    if not TAPE.is_file():
        pytest.fail(f"tape not found: {{TAPE}}")
    return TAPE


def test_step_budget(tape: pathlib.Path) -> None:
    # Fails if a run exceeds 1.5x the {steps} recorded steps.
    testing.assert_max_steps(tape, limit={limit})
'''


def _q(value: str) -> str:
    return json.dumps(value)


def render(meta: TapeMeta, steps: list[Step], tape_name: str) -> str:
    tokens_in = sum(s.llm.input_tokens for s in steps if s.llm)
    tokens_out = sum(s.llm.output_tokens for s in steps if s.llm)
    parts = [
        _HEADER.format(
            version=__version__,
            tape_id=meta.tape_id,
            base=meta.base_commit_sha,
            steps=len(steps),
            tokens_in=tokens_in,
            tokens_out=tokens_out,
            tape_name=tape_name,
            limit=len(steps) * 3 // 2,
        )
    ]
    edited = edited_paths(steps)
    untouched = [g for g in PROTECTED_GLOBS if not any(fnmatch.fnmatchcase(p, g) for p in edited)]
    if untouched:
        globs = "".join(f"            {_q(g)},\n" for g in untouched)
        parts.append(
            "\n\ndef test_protected_paths_untouched(tape: pathlib.Path) -> None:\n"
            "    testing.assert_no_edits_matching(\n"
            "        tape,\n"
            f"        globs=[\n{globs}        ],\n"
            "    )\n"
        )
    tools = list(dict.fromkeys(tool_sequence(steps)))  # distinct, first-occurrence order
    if len(tools) >= 2:
        parts.append(
            "\n\ndef test_tool_order(tape: pathlib.Path) -> None:\n"
            "    testing.assert_tool_called_before(\n"
            "        tape,\n"
            f"        {_q(tools[0])},\n"
            f"        {_q(tools[-1])},\n"
            "    )\n"
        )
    parts.append(
        "\n\ndef test_no_repeated_error_loop(tape: pathlib.Path) -> None:\n"
        "    testing.assert_no_repeated_error_loop(tape, max_repeats=3)\n"
        "\n\ndef test_final_diff_clean(tape: pathlib.Path) -> None:\n"
        "    testing.assert_final_diff_clean(tape)\n"
    )
    return "".join(parts)


def _atomic_write(target: Path, data: bytes) -> None:
    with tempfile.NamedTemporaryFile(dir=target.parent, delete=False) as tmp:
        tmp.write(data)
        tmp.flush()
        os.fsync(tmp.fileno())
    os.replace(tmp.name, target)


def _copy_tape(src: Path, dest: Path) -> None:
    """Consistent single-file copy via the SQLite backup API, then atomic rename."""
    fd, tmp = tempfile.mkstemp(dir=dest.parent, suffix=".tape.tmp")
    os.close(fd)
    try:
        source, target = sqlite3.connect(src), sqlite3.connect(tmp)
        try:
            source.backup(target)
        finally:
            source.close()
            target.close()
        os.replace(tmp, dest)
    finally:
        if os.path.exists(tmp):
            os.unlink(tmp)


def freeze(tape: Path, out: Path) -> Path:
    meta, steps = read_steps(tape)
    out.parent.mkdir(parents=True, exist_ok=True)
    reference = out.with_suffix(".tape")
    if reference.resolve() != tape.resolve():
        _copy_tape(tape, reference)
    _atomic_write(out, render(meta, steps, reference.name).encode())
    return out
